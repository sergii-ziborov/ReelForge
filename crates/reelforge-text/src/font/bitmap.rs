//! Minimal 5×7 bitmap glyphs for printable ASCII (space through `~`).

/// Glyph cell width in pixels.
pub const BITMAP_CELL_W: u32 = 5;
/// Glyph cell height in pixels.
pub const BITMAP_CELL_H: u32 = 7;

/// Return a 5×7 coverage mask for `ch` (1.0 = ink). Unknown → empty cell.
#[must_use]
pub fn bitmap_glyph(ch: char) -> [[f32; 5]; 7] {
    let idx = match ch {
        ' '..='~' => (ch as u8 - b' ') as usize,
        _ => return [[0.0; 5]; 7],
    };
    let rows = FONT[idx];
    let mut out = [[0.0_f32; 5]; 7];
    for (y, row) in rows.iter().enumerate() {
        for (x, cell) in out[y].iter_mut().enumerate() {
            if (row >> (4 - x)) & 1 == 1 {
                *cell = 1.0;
            }
        }
    }
    out
}

