#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn space_is_empty() {
        let g = bitmap_glyph(' ');
        assert!(g.iter().all(|row| row.iter().all(|&v| v == 0.0)));
    }

    #[test]
    fn letter_a_has_ink() {
        let g = bitmap_glyph('A');
        assert!(g.iter().flatten().any(|&v| v > 0.0));
    }
}
